function normalizeLanguage(value) {
  const language = String(value || "").trim().toLowerCase();
  if (language === "en" || language.startsWith("en-")) return "en";
  if (language === "zh" || language === "zh-cn" || language === "zh-sg" ||
      language === "zh-hans" || language.startsWith("zh-hans-")) return "zh-CN";
  return "";
}
function initialLanguage(saved, languages = globalThis.navigator?.languages ||
  [globalThis.navigator?.language]) {
  const explicit = normalizeLanguage(saved);
  if (explicit) return explicit;
  for (const language of languages || []) {
    const normalized = normalizeLanguage(language);
    if (normalized) return normalized;
  }
  return "en";
}
function translateKey(language, key) {
  const normalized = normalizeLanguage(language) || "en";
  return translations[normalized]?.[key] ?? translations.en?.[key] ?? key;
}
function applyStaticTranslations(root, language) {
  root.querySelectorAll("[data-i18n]").forEach((node) => {
    if (!node.dataset.i18nFallback) node.dataset.i18nFallback = node.textContent;
    const value = translateKey(language, node.dataset.i18n);
    node.textContent = value === node.dataset.i18n && node.dataset.i18nFallback
      ? node.dataset.i18nFallback
      : value;
  });
  for (const [selector, datasetKey, attribute] of [
    ["[data-i18n-placeholder]", "i18nPlaceholder", "placeholder"],
    ["[data-i18n-aria-label]", "i18nAriaLabel", "aria-label"],
    ["[data-i18n-title]", "i18nTitle", "title"],
  ]) {
    root.querySelectorAll(selector).forEach((node) => {
      node.setAttribute(attribute, translateKey(language, node.dataset[datasetKey]));
    });
  }
}
